"""Ключи сортировки: естественный порядок для текста и IP-адресов.

Стандартное сравнение строк путает номера и версии: «10» считается
«меньше» «9», порт 443 — «меньше» 80. natural_key сравнивает числа
внутри строк по значению: 9.1 < 10.2, порт 80 < 443,
дата 2026-09-01 < 2026-11-08. Используется моделью таблицы устройств
(sort()) и элементами таблиц с естественной сортировкой (ui/sort_items).
"""

import re

_DIGIT_RE = re.compile(r"(\d+)")


def natural_key(text) -> tuple:
    """Разбирает текст на куски: цифры -> числа, остальное -> строки.

    'v10.2-beta' -> (('t','v'), ('n',10), ('t','.'), ('n',2), ('t','-beta')).
    Числа сравниваются по значению, текст — без учёта регистра; пустой
    ввод даёт () и оказывается в начале списка.
    """
    parts = _DIGIT_RE.split(str(text or "").casefold())
    key = []
    for index, chunk in enumerate(parts):
        if index % 2:                       # нечётные позиции — цифры
            key.append(("n", int(chunk), ""))
        elif chunk:
            key.append(("t", 0, chunk))
    return tuple(key)


def ip_key(text) -> tuple:
    """'192.168.1.10' -> октеты числами (1.9 < 1.10); не-IP — в конец.

    Возвращает (0, о1, о2, о3, о4) для адреса из четырёх чисел и
    (1, natural_key(...)) для всего остального — так «кривые» значения
    всегда оказываются после настоящих адресов.
    """
    parts = str(text or "").strip().split(".")
    if len(parts) == 4 and all(part.isdigit() for part in parts):
        return (0,) + tuple(int(part) for part in parts)
    return (1,) + natural_key(text)
