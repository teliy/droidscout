_current_lang = None


def detect_language() -> str:
    """Язык из настроек; 'auto' — по локали ОС."""
    setting = config.get("language", "auto")
    if setting in ("ru", "en"):
        return setting
    for candidate in (os.environ.get("LC_ALL"), os.environ.get("LANG"),
                      (locale.getlocale() or [""])[0], os.environ.get("LANGUAGE")):
        if candidate and candidate.lower().startswith("ru"):
            return "ru"
    return "en"


def set_language(lang: str) -> None:
    global _current_lang
    _current_lang = lang


def tr(key: str, **kwargs) -> str:
    lang = _current_lang or detect_language()
    text = STRINGS.get(lang, STRINGS["en"]).get(key) or STRINGS["en"].get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text
